-- =========================================================================
-- V1: Criação de Tabelas, Constraints e Índices (Oracle 19c)
-- =========================================================================

-- 1. TELEFONE
CREATE TABLE telefone (
    id_telefone NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    num_ddd     VARCHAR2(2) NOT NULL,
    num_tel     VARCHAR2(9) NOT NULL,
    CONSTRAINT telefone_pk PRIMARY KEY (id_telefone)
);

-- 2. ESTADO
CREATE TABLE estado (
    id_estado   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome_estado VARCHAR2(30) NOT NULL,
    CONSTRAINT estado_pk PRIMARY KEY (id_estado)
);

-- 3. CIDADE
CREATE TABLE cidade (
    id_cidade        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome_cidade      VARCHAR2(30) NOT NULL,
    estado_id_estado NUMBER(19) NOT NULL,
    CONSTRAINT cidade_pk PRIMARY KEY (id_cidade),
    CONSTRAINT cidade_estado_fk FOREIGN KEY (estado_id_estado) REFERENCES estado(id_estado)
);

-- 4. BAIRRO
CREATE TABLE bairro (
    id_bairro        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome_bairro      VARCHAR2(30) NOT NULL,
    cidade_id_cidade NUMBER(19) NOT NULL,
    CONSTRAINT bairro_pk PRIMARY KEY (id_bairro),
    CONSTRAINT bairro_cidade_fk FOREIGN KEY (cidade_id_cidade) REFERENCES cidade(id_cidade)
);

-- 5. ENDERECO
CREATE TABLE endereco (
    id_endereco      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    cep              VARCHAR2(8) NOT NULL,
    rua              VARCHAR2(150) NOT NULL,
    numero           VARCHAR2(5) NOT NULL,
    bairro_id_bairro NUMBER(19) NOT NULL,
    CONSTRAINT endereco_pk PRIMARY KEY (id_endereco),
    CONSTRAINT endereco_bairro_fk FOREIGN KEY (bairro_id_bairro) REFERENCES bairro(id_bairro)
);

-- 6. USUARIO
CREATE TABLE usuario (
    id_usuario           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome                 VARCHAR2(100) NOT NULL,
    email                VARCHAR2(50) NOT NULL,
    senha                VARCHAR2(60) NOT NULL,
    role                 VARCHAR2(10) NOT NULL,
    telefone_id_telefone NUMBER(19) NOT NULL,
    endereco_id_endereco NUMBER(19) NOT NULL,
    CONSTRAINT usuario_pk PRIMARY KEY (id_usuario),
    CONSTRAINT usuario_email_un UNIQUE (email),
    CONSTRAINT ck_usuario_role CHECK (role IN ('ADMIN', 'COMUM', 'PREMIUM')),
    CONSTRAINT usuario_telefone_fk FOREIGN KEY (telefone_id_telefone) REFERENCES telefone(id_telefone),
    CONSTRAINT usuario_endereco_fk FOREIGN KEY (endereco_id_endereco) REFERENCES endereco(id_endereco)
);
CREATE UNIQUE INDEX usuario__idx ON usuario(telefone_id_telefone ASC);

-- 7. RACA
CREATE TABLE raca (
    id_raca   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome_raca VARCHAR2(30) NOT NULL,
    CONSTRAINT raca_pk PRIMARY KEY (id_raca)
);

-- 8. PET
CREATE TABLE pet (
    id_pet       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome         VARCHAR2(30) NOT NULL,
    data_nasc    DATE NOT NULL,
    sexo         VARCHAR2(1) NOT NULL,
    porte        VARCHAR2(10) NOT NULL,
    castrado     NUMBER(1) NOT NULL,
    raca_id_raca NUMBER(19) NOT NULL,
    CONSTRAINT pet_pk PRIMARY KEY (id_pet),
    CONSTRAINT ck_pet_sexo CHECK (sexo IN ('F', 'M')),
    CONSTRAINT ck_pet_porte CHECK (porte IN ('GRANDE', 'MEDIO', 'PEQUENO')),
    CONSTRAINT ck_pet_castrado CHECK (castrado IN (0, 1)),
    CONSTRAINT pet_raca_fk FOREIGN KEY (raca_id_raca) REFERENCES raca(id_raca)
);

-- 9. USUARIO_PET
CREATE TABLE usuario_pet (
    usuario_id_usuario NUMBER(19) NOT NULL,
    pet_id_pet         NUMBER(19) NOT NULL,
    respon_princ       NUMBER(1) NOT NULL,
    CONSTRAINT usuario_pet_pk PRIMARY KEY (usuario_id_usuario, pet_id_pet),
    CONSTRAINT ck_usuario_pet_princ CHECK (respon_princ IN (0, 1)),
    CONSTRAINT usuario_pet_usuario_fk FOREIGN KEY (usuario_id_usuario) REFERENCES usuario(id_usuario),
    CONSTRAINT usuario_pet_pet_fk FOREIGN KEY (pet_id_pet) REFERENCES pet(id_pet)
);

-- 10. STATUS
CREATE TABLE status (
    id_status   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome_status VARCHAR2(15) NOT NULL,
    CONSTRAINT status_pk PRIMARY KEY (id_status),
    CONSTRAINT ck_status_nome CHECK (nome_status IN ('CONCLUIDO', 'EXPIRADO', 'PENDENTE'))
);

-- 11. TAREFA
CREATE TABLE tarefa (
    id_tarefa          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    titulo             VARCHAR2(30) NOT NULL,
    pontos_tarefa      NUMBER(10) NOT NULL,
    descricao          VARCHAR2(200) NOT NULL,
    criacao            TIMESTAMP(6) NOT NULL,
    prazo              TIMESTAMP(6) NOT NULL,
    conclusao          TIMESTAMP(6),
    pet_id_pet         NUMBER(19) NOT NULL,
    status_id_status   NUMBER(19) NOT NULL,
    usuario_id_usuario NUMBER(19) NOT NULL,
    CONSTRAINT tarefa_pk PRIMARY KEY (id_tarefa),
    CONSTRAINT ck_tarefa_pontos CHECK (pontos_tarefa BETWEEN 0 AND 10),
    CONSTRAINT tarefa_pet_fk FOREIGN KEY (pet_id_pet) REFERENCES pet(id_pet),
    CONSTRAINT tarefa_status_fk FOREIGN KEY (status_id_status) REFERENCES status(id_status),
    CONSTRAINT tarefa_usuario_fk FOREIGN KEY (usuario_id_usuario) REFERENCES usuario(id_usuario)
);

-- 12. TRILHA
CREATE TABLE trilha (
    id_trilha  NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome       VARCHAR2(30) NOT NULL,
    descricao  VARCHAR2(200) NOT NULL,
    pet_id_pet NUMBER(19) NOT NULL,
    CONSTRAINT trilha_pk PRIMARY KEY (id_trilha),
    CONSTRAINT trilha_pet_fk FOREIGN KEY (pet_id_pet) REFERENCES pet(id_pet)
);

-- 13. MODULO
CREATE TABLE modulo (
    id_modulo        NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome             VARCHAR2(50) NOT NULL,
    tempo_conclusao  VARCHAR2(10) NOT NULL,
    descricao        VARCHAR2(100) NOT NULL,
    trilha_id_trilha NUMBER(19) NOT NULL,
    CONSTRAINT modulo_pk PRIMARY KEY (id_modulo),
    CONSTRAINT modulo_trilha_fk FOREIGN KEY (trilha_id_trilha) REFERENCES trilha(id_trilha)
);

-- 14. AULA
CREATE TABLE aula (
    id_aula          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    nome             VARCHAR2(50) NOT NULL,
    descricao        VARCHAR2(100) NOT NULL,
    pontos_aula      NUMBER(10) NOT NULL,
    dificuldade      VARCHAR2(20) NOT NULL,
    concluida        NUMBER(1) NOT NULL,
    modulo_id_modulo NUMBER(19) NOT NULL,
    CONSTRAINT aula_pk PRIMARY KEY (id_aula),
    CONSTRAINT ck_aula_concluida CHECK (concluida IN (0, 1)),
    CONSTRAINT aula_modulo_fk FOREIGN KEY (modulo_id_modulo) REFERENCES modulo(id_modulo)
);

-- 15. HISTORICO
CREATE TABLE historico (
    id_hist    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    tipo_hist  VARCHAR2(30) NOT NULL,
    data_hist  TIMESTAMP(6) NOT NULL,
    pet_id_pet NUMBER(19) NOT NULL,
    CONSTRAINT historico_pk PRIMARY KEY (id_hist),
    CONSTRAINT historico_pet_fk FOREIGN KEY (pet_id_pet) REFERENCES pet(id_pet)
);

-- 16. AUDITORIA DML TAREFA
CREATE TABLE auditoria_dml_tarefa (
    id_auditoria       NUMBER(19) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nome_usuario       VARCHAR2(50) NOT NULL,
    tipo_operacao      VARCHAR2(10) NOT NULL,
    data_hora_operacao TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    valores_anteriores VARCHAR2(4000),
    valores_novos      VARCHAR2(4000)
);

-- ÍNDICES EM FKs PARA PERFORMANCE
CREATE INDEX idx_cidade_estado ON cidade(estado_id_estado);
CREATE INDEX idx_bairro_cidade ON bairro(cidade_id_cidade);
CREATE INDEX idx_endereco_bairro ON endereco(bairro_id_bairro);
CREATE INDEX idx_usuario_endereco ON usuario(endereco_id_endereco);
CREATE INDEX idx_pet_raca ON pet(raca_id_raca);
CREATE INDEX idx_usuario_pet_pet ON usuario_pet(pet_id_pet);
CREATE INDEX idx_tarefa_pet ON tarefa(pet_id_pet);
CREATE INDEX idx_tarefa_status ON tarefa(status_id_status);
CREATE INDEX idx_tarefa_usuario ON tarefa(usuario_id_usuario);
CREATE INDEX idx_trilha_pet ON trilha(pet_id_pet);
CREATE INDEX idx_modulo_trilha ON modulo(trilha_id_trilha);
CREATE INDEX idx_aula_modulo ON aula(modulo_id_modulo);
CREATE INDEX idx_historico_pet ON historico(pet_id_pet);